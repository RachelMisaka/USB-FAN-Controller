/**
  * @brief  Force a clean USB re-enumeration on every boot.
  *         The Blue Pill D+ pull-up is hard-wired to 3.3V, so a MCU reset
  *         never drops the "device connected" state and the host does not
  *         re-enumerate (flash or reset leaves the device dead until replug).
  *         Drive DP/DM low for ~50 ms (SE0) to signal a disconnect, then let
  *         MX_USB_DEVICE_Init restore the pins as USB alternate function so
  *         the pull-up re-asserts "connect" and the host enumerates cleanly.
  */
static void UsbForceReEnumerate(void)
{
  GPIO_InitTypeDef gpio = {0};

  __HAL_RCC_GPIOA_CLK_ENABLE();

  gpio.Pin = GPIO_PIN_11 | GPIO_PIN_12;
  gpio.Mode = GPIO_MODE_OUTPUT_PP;
  gpio.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(GPIOA, &gpio);
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_11 | GPIO_PIN_12, GPIO_PIN_RESET);
  HAL_Delay(50U);
}
